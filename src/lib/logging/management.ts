import { createHash, randomUUID } from "node:crypto";
import { db } from "../db.ts";
import { recordAuditLog } from "../audit.ts";
import { readLogSettings, saveLogSettings, normalizeLogSettings } from "./settings.ts";
import { cleanupCandidates, removeLogFiles, withLogLease, type LogFile } from "./store.ts";
import type { LogCleanupPreview, LogCleanupResult, LogSettings } from "./types.ts";

interface Preview { actorId: string; expires: number; cutoff: number; auditCount: number; files: LogFile[]; settings: LogSettings; currentHash: string; }
const hash = (value: unknown) => createHash("sha256").update(JSON.stringify(value)).digest("hex");
export function previewCleanup(actorId: string, patch: unknown = {}): LogCleanupPreview {
  const current = readLogSettings();
  const settings = normalizeLogSettings(patch, current);
  const cutoff = settings.auditRetentionDays ? Date.now() - settings.auditRetentionDays * 86400_000 : 0;
  const auditCount = Number(db.prepare("SELECT COUNT(*) AS c FROM audit_logs WHERE created_at < ?").get(cutoff)?.c ?? 0);
  const files = cleanupCandidates(settings);
  const token = randomUUID();
  const preview: Preview = { actorId, expires: Date.now() + 5 * 60_000, cutoff, auditCount, files, settings, currentHash: hash(current) };
  db.prepare("DELETE FROM system_settings WHERE key LIKE 'logging_preview_%' AND updated_at < ?").run(Date.now() - 5 * 60_000);
  db.prepare("INSERT INTO system_settings(key, value, updated_at) VALUES (?, ?, ?)").run(`logging_preview_${token}`, JSON.stringify(preview), Date.now());
  return { token, expiresAt: preview.expires, auditCount, files: files.length, bytes: files.reduce((n, f) => n + f.bytes, 0), settings };
}
function getPreview(actorId: string, token: string): Preview {
  if (!/^[a-f0-9-]{36}$/.test(token)) throw new Error("Invalid cleanup preview");
  const row = db.prepare("SELECT value FROM system_settings WHERE key = ?").get(`logging_preview_${token}`) as { value: string } | undefined;
  if (!row) throw new Error("Cleanup preview expired");
  const preview = JSON.parse(row.value) as Preview;
  if (preview.actorId !== actorId || preview.expires < Date.now() || preview.currentHash !== hash(readLogSettings())) throw new Error("Cleanup preview expired or settings changed");
  return preview;
}
export function updateLogSettings(actorId: string, patch: unknown, token?: string) {
  return withLogLease(() => {
    const current = readLogSettings();
    const settings = normalizeLogSettings(patch, current);
    const shortening = settings.auditRetentionDays !== 0 && (current.auditRetentionDays === 0 || settings.auditRetentionDays < current.auditRetentionDays);
    if (shortening) {
      const preview = getPreview(actorId, token ?? "");
      // Debug expiry is generated by the server during preview; confirmation may arrive later.
      if (settings.level === "debug" && preview.settings.level === "debug") settings.debugUntil = preview.settings.debugUntil;
      if (hash(preview.settings) !== hash(settings)) throw new Error("Settings differ from cleanup preview");
    }
    db.exec("BEGIN IMMEDIATE");
    try {
      recordAuditLog({ userId: actorId, action: "logs.settings.updated", details: JSON.stringify(Object.keys(settings).filter(key => JSON.stringify(current[key as keyof LogSettings]) !== JSON.stringify(settings[key as keyof LogSettings])).map(field => ({ field, from: current[field as keyof LogSettings], to: settings[field as keyof LogSettings] }))) });
      saveLogSettings(settings);
      if (token) db.prepare("DELETE FROM system_settings WHERE key = ?").run(`logging_preview_${token}`);
      db.exec("COMMIT");
    } catch (error) { db.exec("ROLLBACK"); saveLogSettings(current); throw error; }
    return settings;
  });
}
export function executeCleanup(actorId: string, token: string): LogCleanupResult {
  return withLogLease(() => {
    const preview = getPreview(actorId, token);
    // A cleanup preview cannot secretly change retention settings.
    if (hash(preview.settings) !== hash(readLogSettings())) throw new Error("Apply settings before cleanup");
    db.exec("BEGIN IMMEDIATE");
    try {
      db.prepare("DELETE FROM system_settings WHERE key = ?").run(`logging_preview_${token}`);
      const auditCount = Number(db.prepare("DELETE FROM audit_logs WHERE created_at < ?").run(preview.cutoff).changes);
      recordAuditLog({ userId: actorId, action: "logs.cleanup.executed", details: `auditCount=${auditCount}; files=${preview.files.length}` });
      db.exec("COMMIT");
      // Files are a separate resource. Failures are reported, never claimed atomic.
      try { const result = removeLogFiles(preview.files); return { auditCount, ...result, partial: result.failed > 0 }; }
      catch { return { auditCount, removed: 0, releasedBytes: 0, partial: true }; }
    } catch (error) { if (db.isTransaction) db.exec("ROLLBACK"); throw error; }
  });
}
export function cleanupAuditRetention(): number {
  const days = readLogSettings().auditRetentionDays;
  if (!days) return 0;
  db.exec("BEGIN IMMEDIATE");
  try {
    const removed = Number(db.prepare("DELETE FROM audit_logs WHERE created_at < ?").run(Date.now() - days * 86400_000).changes);
    if (removed) recordAuditLog({ userId: "system", action: "logs.cleanup.scheduled", details: `auditCount=${removed}` });
    db.exec("COMMIT"); return removed;
  } catch (error) { db.exec("ROLLBACK"); throw error; }
}

import { after, it } from "node:test";
import assert from "node:assert/strict";
import { db } from "../db.ts";
import { buildFullExportPayload, parseFullImportPayload } from "../admin-system.ts";
import { getUserData, saveUserCategories, saveUserLinks, saveUserProjects, saveUserTodos, saveUserConfigs } from "../user-data.ts";
import { createProject } from "../todos-projects.ts";

const ids = ["json-backup-source", "json-backup-restored"];
for (const id of ids) db.prepare("INSERT INTO users (id, username, password_hash, created_at) VALUES (?, ?, 'hash', ?)").run(id, id, Date.now());
after(() => { for (const id of ids) db.prepare("DELETE FROM users WHERE id = ?").run(id); });
it("roundtrips product export/import functions and persisted public field shapes", () => {
  const [source, target] = ids;
  saveUserCategories(source, [{ id: "cat", name: "开发", label: "Dev", icon: "🛠️", color: "#10B981" }]);
  saveUserLinks(source, [{ id: "link", title: "GitHub", url: "https://github.com", category: "cat", description: "中文", icon: "", isQuickAccess: true, notes: "private note" }]);
  createProject(source, { name: "Project", status: "研究中", todos: [{ title: "milestone", priority: "high", dueDate: "2026-10-14" }] });
  saveUserConfigs(source, { theme: "dark", language: "en", clockWidgetMode: "analog" });
  const original = getUserData(source);
  const exported = buildFullExportPayload({ scope: "personal", dbData: original, fallbackConfig: original.config, fallbackCategories: [], fallbackLinks: [], localStorageData: { focusTracker: null, quickNotes: null, linkUsage: null } });
  const imported = parseFullImportPayload(JSON.parse(JSON.stringify(exported)));
  saveUserCategories(target, imported.categories);
  saveUserLinks(target, imported.links);
  saveUserProjects(target, imported.projects as Parameters<typeof saveUserProjects>[1]);
  saveUserTodos(target, imported.todos as Parameters<typeof saveUserTodos>[1]);
  saveUserConfigs(target, imported.config ?? {});
  const restored = getUserData(target);
  assert.deepEqual(restored.categories, original.categories);
  assert.deepEqual(restored.links, original.links);
  assert.deepEqual(restored.projects, original.projects);
  assert.equal(restored.todos.length, 1);
  assert.equal(restored.todos[0].title, original.todos[0].title);
  assert.equal(restored.todos[0].dueDate, original.todos[0].dueDate);
  assert.equal(restored.todos[0].priority, "high");
  assert.equal(restored.todos[0].ownerId, target);
  assert.equal(restored.config.theme, "dark");
  assert.equal(restored.config.language, "en");
  assert.equal(restored.config.clockWidgetMode, "analog");
  assert.equal(imported.config?.aiApiKey, undefined);
});

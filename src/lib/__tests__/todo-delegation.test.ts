import { after, it } from "node:test";
import assert from "node:assert/strict";
import { db } from "../db.ts";
import { createTodo, updateTodoFields } from "../todos-projects.ts";
import { getUserTodos, resolveTodoOwner } from "../todo-store.ts";
const manager = "delegation-manager", member = "delegation-member", stranger = "delegation-stranger";
for (const id of [manager, member, stranger]) db.prepare("INSERT INTO users (id, username, password_hash, role, created_at) VALUES (?, ?, 'hash', ?, ?)").run(id, id, id === manager ? "admin" : "user", Date.now());
after(() => { for (const id of [manager, member, stranger]) db.prepare("DELETE FROM users WHERE id = ?").run(id); });
it("uses the production inbox and ownership resolver to complete a delegated task", () => {
  const id = createTodo(manager, { title: "完成 API 联调", assigneeId: member });
  assert.equal(getUserTodos(stranger).length, 0);
  const task = getUserTodos(member)[0];
  assert.equal(task.ownerId, manager);
  assert.equal(task.isDelegated, true);
  assert.equal(resolveTodoOwner(id, stranger), null);
  const owner = resolveTodoOwner(id, member);
  assert.equal(owner, manager);
  updateTodoFields(id, owner!, { done: true });
  assert.equal(getUserTodos(manager)[0].done, true);
});
